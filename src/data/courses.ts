const buildCurriculum = (prefix: string, titles: string[]): Course['curriculum'] => {
  const half = Math.ceil(titles.length / 2);
  const mk = (title: string, i: number): Course['curriculum'][number]['lessons'][number] => ({
    id: `${prefix}-l${i + 1}`,
    title,
    duration: `${8 + i * 3}:${String((i * 7) % 60).padStart(2, '0')}`,
    videoUrl: SAMPLE_VIDEO,
    description: `Lesson covering ${title}.`,
    isPreview: i === 0,
    resources: [{ id: `${prefix}-r${i}`, title: 'Lesson slides', type: 'pdf', size: '1.2 MB' }],
  });
  return [
    { id: `${prefix}-s1`, title: 'Getting Started', lessons: titles.slice(0, half).map(mk) },
    { id: `${prefix}-s2`, title: 'Core Concepts', lessons: titles.slice(half).map((t, i) => mk(t, half + i)) },
  ];
};

